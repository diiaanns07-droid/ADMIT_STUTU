"""Простая эвристика по ключевым словам RU/KK — baseline для сравнения и безопасный fallback.

Не обучается. Считает совпадения основ слов по меткам; при равенстве — порядок PRIORITY;
без совпадений — other с needs_review. Списки основ написаны до просмотра тестовых данных.
"""

from __future__ import annotations

from ml.civic_classifier.text import normalize

STEMS = {
    "lighting": ("фонар", "освещ", "светильник", "лампа", "лампоч", "темно", "темн", "не горит", "не горят",
                 "горят днем", "мигает", "шам ", "шамдар", "жарық", "қараңғы", "жанбайды", "жанып"),
    "transport_stops": ("остановк", "павильон", "табло", "автобус", "маршрут", "аялдама", "аялдамада",
                        "посадк", "троллейбус"),
    "sidewalks": ("тротуар", "пешеход", "плитк", "бордюр", "пандус", "коляск", "переход", "дорожк",
                  "жаяу", "плитка", "өткел"),
    "roads": ("дорог", "яма", "ямы", "выбоин", "асфальт", "разметк", "светофор", "проезж", "трасс", "знак",
              "лежачий", "жол", "шұңқыр", "бағдаршам", "асфальт"),
    "landscaping": ("дерев", "деревь", "газон", "сквер", "парк", "детск", "площадк", "скамейк", "клумб",
                    "благоустр", "озелен", "фонтан", "ағаш", "саябақ", "алаң", "гүл", "көгал", "абаттандыр"),
    "other": ("мусор", "шум", "собак", "вода", "отоплен", "спасибо", "қоқыс", "шу ", "ит ", "рақмет", "су жоқ"),
}
PRIORITY = ("lighting", "transport_stops", "sidewalks", "roads", "landscaping", "other")


def keyword_hits(text: str) -> dict[str, int]:
    """Число совпавших основ по каждой метке (используется и эвристикой, и гибридной моделью)."""
    t = " " + normalize(text) + " "
    return {label: sum(1 for stem in STEMS[label] if stem in t) for label in PRIORITY}


def heuristic_label(text: str) -> tuple[str, int]:
    """(метка, число совпадений). 0 совпадений -> ('other', 0)."""
    hits = keyword_hits(text)
    best, best_hits = "other", 0
    for label in PRIORITY:
        if hits[label] > best_hits:
            best, best_hits = label, hits[label]
    return best, best_hits
